"""Generate TypeScript reader types from the shipped schema, never hand-copy fields."""

import json
from pathlib import Path


def ts(s):
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(x) for x in s["enum"])
    if "oneOf" in s:
        return " | ".join(ts(x) for x in s["oneOf"])
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    kind = s.get("type")
    if kind == "string":
        return "string"
    if kind == "integer":
        return "number"
    if kind == "null":
        return "null"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        if s.get("minItems") == s.get("maxItems") and "maxItems" in s:
            return "[" + ", ".join(ts(s["items"]) for _ in range(s["maxItems"])) + "]"
        return "Array<" + ts(s["items"]) + ">"
    if kind == "object":
        if not s.get("properties") and isinstance(s.get("additionalProperties"), dict):
            return "Record<string, " + ts(s["additionalProperties"]) + ">"
        if not s.get("properties") and s.get("additionalProperties") is True:
            return "Record<string, unknown>"
        return (
            "{ "
            + "; ".join(
                json.dumps(k)
                + ("" if k in s.get("required", []) else "?")
                + ": "
                + ts(v)
                for k, v in s.get("properties", {}).items()
            )
            + " }"
        )
    return "unknown"


def generate():
    schema = json.loads(Path(__file__).with_name("document-1.0.0.json").read_text())
    lines = [
        "// Generated by schema/generate_types.py. Offsets are Unicode code points."
    ]
    for name, s in schema["$defs"].items():
        if name == "Block":
            variants = []
            for branch in s["allOf"]:
                variant = dict(s, properties=dict(s["properties"]))
                variant["properties"]["type"] = branch["if"]["properties"]["type"]
                variant["properties"]["payload"] = branch["then"]["properties"][
                    "payload"
                ]
                variants.append(ts(variant))
            body = " | ".join(variants)
        else:
            body = ts(s)
        lines.append("export type " + name + " = " + body + ";")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(__file__).with_name("document-1.0.0.ts").write_text(generate())
